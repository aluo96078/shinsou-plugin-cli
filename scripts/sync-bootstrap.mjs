// Copies the app's JavaScript bridge bootstrap (Jsoup-compatible DOM, SManga/SChapter/Page helpers,
// `bridge.*` over `__shinsouBridge`) into src/runner/legacy-bootstrap.ts for `shinsou-plugin test`.
//
//   node scripts/sync-bootstrap.mjs [path/to/shinsoux]
//
// TODO(sandbox-core): once the app's sandbox-core WASM guest is published, run hooks in it instead
// of QuickJS + this bootstrap, so `test` executes byte-for-byte what the app executes.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const app = process.argv[2] ?? join(import.meta.dirname, "../../shinsoux");
const file = join(app, "composeApp/src/iosMain/kotlin/dev/shinsou/kmp/plugin/IosJavaScriptBootstrap.kt");
const kt = readFileSync(file, "utf8");
const m = /IOS_JAVASCRIPTCORE_BOOTSTRAP: String = """\n([\s\S]*?)\n"""/.exec(kt);
if (!m) throw new Error(`bootstrap constant not found in ${file}`);
if (/\$\{|\$[A-Za-z_]/.test(m[1])) throw new Error("bootstrap uses Kotlin string templates; extend this script");
const out =
  "// GENERATED by scripts/sync-bootstrap.mjs from the Shinsou X app\n" +
  "// (composeApp/src/iosMain/kotlin/dev/shinsou/kmp/plugin/IosJavaScriptBootstrap.kt). Do not edit.\n" +
  `export const LEGACY_BOOTSTRAP: string = ${JSON.stringify(m[1])};\n`;
writeFileSync(join(import.meta.dirname, "../src/runner/legacy-bootstrap.ts"), out);
console.log(`legacy-bootstrap.ts: ${m[1].length} characters`);
